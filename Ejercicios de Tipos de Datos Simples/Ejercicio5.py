horas_trabajadas = float(input("¿Cuántas horas has trabajado? "))
coste_por_hora = float(input("¿Cuál es el coste por hora? "))

paga = horas_trabajadas * coste_por_hora
print(f"La paga que te corresponde es: {paga}")

